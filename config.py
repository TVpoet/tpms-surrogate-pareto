# -*- coding: utf-8 -*-
"""
TPMS 代理模型项目 — 全局配置文件

所有几何与材料参数在此统一管理。
修改此文件后，仿真、训练、逆向设计等所有脚本自动同步。
"""

import numpy as np
import os

# ============================================================================
# 几何参数
# ============================================================================

# 单胞尺寸 (m)
L = 0.01  # 10 mm

# TPMS 名义壁厚 (mm)
WALL_THICKNESS_MM = 0.6  # 推荐范围: 0.3–0.8 mm (对于 10 mm 单胞)


# ============================================================================
# 材料参数
# ============================================================================

# 基体材料属性（铝合金）
E_SOLID = 70e9  # 杨氏模量 (Pa)
NU = 0.33       # 泊松比


# ============================================================================
# 位移加载范围
# ============================================================================

# 训练数据的位移采样范围 (m)
# ±3 μm → 应变 ±0.03%，确保严格在线弹性区内
DISPLACEMENT_RANGE = (-3e-6, 3e-6)

# 三轴加载开关
TRIAXIAL_LOADING = True


# ============================================================================
# 派生参数（自动计算，无需修改）
# ============================================================================

def get_thickness_parameter():
    """将物理壁厚 (mm) 转换为 φ 空间的 THICKNESS 参数"""
    return WALL_THICKNESS_MM / ((L / (2 * np.pi)) * 1000)


# ============================================================================
# 文件路径
# ============================================================================

OUTPUTS_DIR = 'outputs'
INP_OUTPUT_DIR = os.path.join(OUTPUTS_DIR, 'abaqus_export')


# ============================================================================
# Abaqus 导出配置
# ============================================================================

class AbaqusConfig:
    """Abaqus INP 导出相关配置"""

    @staticmethod
    def get_shell_thickness():
        """获取壳单元厚度 (mm)"""
        return WALL_THICKNESS_MM

    ELEMENT_TYPE = 'S4R'
    MESH_DENSITY = 20
    BC_TYPE = 'STRAIN'

    @staticmethod
    def get_material_props():
        return {
            'E': E_SOLID,
            'nu': NU,
            'name': 'Aluminum_Alloy'
        }

    OUTPUT_STRESS = True
    OUTPUT_STRAIN = True
    OUTPUT_DISPLACEMENT = True


if __name__ == "__main__":
    print(f"L = {L*1000:.1f} mm")
    print(f"壁厚 = {WALL_THICKNESS_MM:.1f} mm")
    print(f"E = {E_SOLID/1e9:.1f} GPa, ν = {NU}")
    print(f"位移范围 = ±{DISPLACEMENT_RANGE[1]*1e6:.0f} μm")
